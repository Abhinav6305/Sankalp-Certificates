#!/usr/bin/env python3
"""
Regenerates js/data.js from data/participants.csv.

Run this after editing the CSV (fixing a spelling, adding the participants
who registered without an email address, etc.):

    python build/build_data.py

CSV columns:  Name, Email, Year, Department
Output:       js/data.js  ->  const PARTICIPANTS = { "<email>": [ {n,y,d}, ... ] }

An email may map to more than one participant; the site then shows a
"which one are you?" picker.
"""

import csv, json, os, sys, collections

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
CSV_IN = os.path.join(ROOT, 'data', 'participants.csv')
JS_OUT = os.path.join(ROOT, 'js', 'data.js')

VALID_YEARS = {'I', 'II', 'III', 'IV'}


def main():
    if not os.path.exists(CSV_IN):
        sys.exit('Missing ' + CSV_IN)

    data = collections.OrderedDict()
    problems = []

    with open(CSV_IN, newline='', encoding='utf-8-sig') as f:
        for i, row in enumerate(csv.DictReader(f), start=2):
            name = (row.get('Name') or '').strip()
            email = (row.get('Email') or '').strip().lower().replace(' ', '')
            year = (row.get('Year') or '').strip().upper()
            dept = (row.get('Department') or '').strip().upper()

            if not name:
                problems.append('row %d: no name' % i); continue
            if not email or '@' not in email:
                problems.append('row %d: %s has no usable email' % (i, name)); continue
            if year not in VALID_YEARS:
                problems.append('row %d: %s has year "%s"' % (i, name, year))
            if not dept:
                problems.append('row %d: %s has no department' % (i, name))

            data.setdefault(email, [])
            if not any(p['n'].lower() == name.lower() for p in data[email]):
                data[email].append({'n': name, 'y': year, 'd': dept})

    payload = json.dumps(data, ensure_ascii=False, separators=(',', ':'))
    people = sum(len(v) for v in data.values())

    with open(JS_OUT, 'w', encoding='utf-8') as f:
        f.write('/* AUTO-GENERATED by build/build_data.py — edit data/participants.csv instead. */\n')
        f.write('/* %d participants across %d email addresses. */\n' % (people, len(data)))
        f.write('const PARTICIPANTS = %s;\n' % payload)

    print('Wrote %s — %d participants, %d emails' % (os.path.relpath(JS_OUT, ROOT), people, len(data)))

    shared = [(e, [p['n'] for p in v]) for e, v in data.items() if len(v) > 1]
    for email, names in shared:
        print('  shared email: %s -> %s' % (email, ', '.join(names)))
    for p in problems:
        print('  WARNING %s' % p)


if __name__ == '__main__':
    main()
